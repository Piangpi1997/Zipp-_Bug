package com.zipbug.base.creator

import com.zipbug.base.termux.LogSanitizer
import org.json.JSONArray
import org.json.JSONObject

/**
 * Generates a standard React + Vite source project.
 *
 * This is intentionally source-only. Zip_Bug does not auto-run npm scripts from
 * imported ZIPs because package lifecycle scripts can execute arbitrary code.
 * Build the exported project in a reviewed Termux workspace, then import the
 * built static output as a normal web mini-app.
 */
object ReactViteScaffolder {
    fun files(
        name: String,
        goal: String
    ): Map<String, String> {
        require(name.isNotBlank()) { "App name is required" }
        require(name.length <= 60) { "App name is too long" }
        require(goal.length <= 4000) { "Goal is too long" }

        val safeGoal = LogSanitizer.sanitize(goal)
        val slug = name.lowercase()
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')
            .ifBlank  { "zipbug-react-app" }

        val manifest = JSONObject()
            .put("name", name)
            .put("slug", slug)
            .put("version", "1.0.0")
            .put("kind", "react-vite-source")
            .put("entry", "index.html")
            .put("permissions", JSONArray())
            .put(
                "requiredTools",
                JSONArray().put("node").put("npm")
            )
            .toString(2) + "\n"

        val packageJson = JSONObject()
            .put("name", slug)
            .put("private", true)
            .put("version", "1.0.0")
            .put("type", "module")
            .put(
                "scripts",
                JSONObject()
                    .put("dev", "vite")
                    .put("build", "vite build")
                    .put("preview", "vite preview")
            )
            .put(
                "dependencies",
                JSONObject()
                    .put("react", "^18.3.1")
                    .put("react-dom", "^18.3.1")
            )
            .put(
                "devDependencies",
                JSONObject()
                    .put("@vitejs/plugin-react", "^4.3.4")
                    .put("vite", "^5.4.14")
            )
            .toString(2) + "\n"

        val index = """
            <!doctype html>
            <html lang="en">
              <head>
                <meta charset="UTF-8" />
                <meta name="viewport" content="width=device-width, initial-scale=1.0" />
                <meta name="theme-color" content="#121212" />
                <title>__TITLE__</title>
              </head>
              <body>
                <div id="root"></div>
                <script type="module" src="/src/main.jsx"></script>
              </body>
            </html>
        """.trimIndent()
            .replace("__TITLE__", html(name)) + "\n"

        val mainJsx = """
            import React from 'react'
            import ReactDOM from 'react-dom/client'
            import App from './App.jsx'
            import './styles.css'

            ReactDOM.createRoot(document.getElementById('root')).render(
              <React.StrictMode>
                <App />
              </React.StrictMode>,
            )
        """.trimIndent() + "\n"

        val appJsx = """
            import { useState } from 'react'

            const goal = __GOAL_JSON__

            export default function App() {
              const [count, setCount] = useState(0)

              return (
                <main className="shell">
                  <div className="badge">ZIP_BUG • REACT + VITE</div>
                  <h1>__TITLE_JSX__</h1>
                  <p>{goal || 'Generated by Zip_Bug Antigravity Studio.'}</p>

                  <button type="button" onClick={() => setCount((value) => value + 1)}>
                    React state test: {count}
                  </button>

                  <div className="status">
                    Source project ready. Build with Vite to create dist/.
                  </div>
                </main>
              )
            }
        """.trimIndent()
            .replace("__GOAL_JSON__", JSONObject.quote(safeGoal))
            .replace("__TITLE_JSX__", jsxText(name)) + "\n"

        val css = """
            :root {
              color-scheme: dark;
            font-family: Inter, ui-sans-serif, system-ui, sans-serif;
              background: #121212;
              color: #f7f3ef;
            }

            * { box-sizing: border-box; }

            body {
              margin: 0;
              min-width: 320px;
              min-height: 100vh;
              display: grid;
              place-items: center;
              background:
                radial-gradient(circle at top, #2a1a10 0, #121212 42%);
            }

            .shell {
              width: min(92vw, 680px);
              padding: 28px;
              border: 1px solid #36302d;
              border-radius: 24px;
              background: #1b1b1b;
              box-shadow: 0 22px 70px rgba(0, 0, 0, 0.35);
            }

            .badge {
              color: #39d98a;
              font: 800 12px ui-monospace, monospace;
              letter-spacing: .08em;
            }

            h1 {
              margin: 12px 0;
              font-size: clamp(32px, 9vw, 52px);
            }

            p {
              color: #b8b0aa;
              line-height: 1.65;
            }

            button {
              width: 100%;
              min-height: 48px;
              border: 0;
              border-radius: 14px;
              padding: 14px 18px;
              background: #ff6b00;
              color: #121212;
              font-weight: 800;
              font-size: 16px;
            }

            .status {
              margin-top: 16px;
              padding: 14px;
              border-radius: 14px;
              background: #101010;
              color: #39d98a;
            }
        """.trimIndent() + "\n"

        val viteConfig = """
            import { defineConfig } from 'vite'
            import react from '@vitejs/plugin-react'

            export default defineConfig({
              plugins: [react()],
              base: './',
            })
        """.trimIndent() + "\n"

        val readme = """
            # __TITLE__

            React + Vite source generated by Zip_Bug Antigravity Studio.

            ## Goal

            __GOAL__

            ## Build in a reviewed workspace

            This ZIP is source-only. Zip_Bug deliberately does not execute npm
            lifecycle scripts from imported ZIPs.

            In a Termux workspace you trust, run npm install and npm run build.
            Vite writes the static app to dist/.

            To run the built result inside Zip_Bug, package dist/ as a normal
            web mini-app with an app.json whose entry points to index.html,
            then import that ZIP in Projects.

            React: 18.x
            Vite: 5.x
        """.trimIndent()
            .replace("__TITLE__", name)
            .replace(
                "__GOAL__",
                safeGoal.ifBlank { "No goal provided." }
            ) + "\n"

        return linkedMapOf(
            "app.json" to manifest,
            "package.json" to packageJson,
            "index.html" to index,
            "vite.config.js" to viteConfig,
            "src/main.jsx" to mainJsx,
            "src/App.jsx" to appJsx,
            "src/styles.css" to css,
            ".gitignore" to "node_modules/\ndist/\n.vite/\n",
            "README.md" to readme
        )
    }

    private fun html(value: String): String =
        value.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&#39;")

    private fun jsxText(value: String): String =
        value.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
}
