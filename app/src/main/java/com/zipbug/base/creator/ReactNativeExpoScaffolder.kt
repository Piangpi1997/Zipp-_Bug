package com.zipbug.base.creator

import com.zipbug.base.termux.LogSanitizer
import org.json.JSONArray
import org.json.JSONObject

/**
 * Generates a React Native + Expo TypeScript source project.
 *
 * The output is source-only. Zip_Bug never auto-runs npm/npx lifecycle scripts
 * from imported projects. Build and package it only in a reviewed workspace.
 */
object ReactNativeExpoScaffolder {
    private val packageRegex =
        Regex("^[a-zA-Z][a-zA-Z0-9_]*(\\.[a-zA-Z][a-zA-Z0-9_]*)+$")

    fun files(
        name: String,
        packageName: String,
        goal: String
    ): Map<String, String> {
        require(name.isNotBlank()) { "App name is required" }
        require(name.length <= 60) { "App name is too long" }
        require(packageRegex.matches(packageName)) {
            "Invalid Android package name"
        }
        require(goal.length <= 4000) { "Goal is too long" }

        val safeGoal = LogSanitizer.sanitize(goal)
        val slug = name.lowercase()
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')
            .ifBlank { "zipbug-react-native" }

        val manifest = JSONObject()
            .put("name", name)
            .put("slug", slug)
            .put("version", "1.0.0")
            .put("kind", "react-native-expo-source")
            .put("entry", "App.tsx")
            .put("androidPackage", packageName)
            .put("permissions", JSONArray())
            .put(
                "requiredTools",
                JSONArray().put("node").put("npm").put("npx")
            )
            .toString(2) + "\n"

        val packageJson = JSONObject()
            .put("name", slug)
            .put("private", true)
            .put("version", "1.0.0")
            .put("main", "node_modules/expo/AppEntry.js")
            .put(
                "scripts",
                JSONObject()
                    .put("start", "expo start")
                    .put("android", "expo start --android")
                    .put("ios", "expo start --ios")
                    .put("web", "expo start --web")
            )
            .put(
                "dependencies",
                JSONObject()
                    .put("expo", "^52.0.0")
                    .put("react", "18.3.1")
                    .put("react-native", "0.76.9")
            )
            .put(
                "devDependencies",
                JSONObject()
                    .put("@types/react", "~18.3.12")
                    .put("typescript", "^5.3.3")
            )
            .toString(2) + "\n"

        val expoAppJson = JSONObject()
            .put(
                "expo",
                JSONObject()
                    .put("name", name)
                    .put("slug", slug)
                    .put("version", "1.0.0")
                    .put("orientation", "portrait")
                    .put("userInterfaceStyle", "dark")
                    .put(
                        "android",
                        JSONObject().put("package", packageName)
                    )
                    .put("ios", JSONObject())
            )
            .toString(2) + "\n"

        val appTsx = """
            import React, { useState } from 'react'
            import {
              SafeAreaView,
              StatusBar,
              StyleSheet,
              Text,
              TouchableOpacity,
              View,
            } from 'react-native'

            const goal = __GOAL_JSON__
            const title = __TITLE_JSON__

            export default function App() {
              const [count, setCount] = useState(0)

              return (
                <SafeAreaView style={styles.safe}>
                  <StatusBar barStyle="light-content" />
                  <View style={styles.card}>
                    <Text style={styles.badge}>ZIP_BUG • REACT NATIVE + EXPO</Text>
                    <Text style={styles.title}>{title}</Text>
                    <Text style={styles.body}>
                      {goal || 'Generated by Zip_Bug Antigravity Studio.'}
                    </Text>

                    <TouchableOpacity
                      accessibilityRole="button"
                      style={styles.button}
                      onPress={() => setCount((value) => value + 1)}
                    >
                      <Text style={styles.buttonText}>
                        React Native state test: {count}
                      </Text>
                    </TouchableOpacity>

                    <Text style={styles.status}>
                      Source project ready for a reviewed Expo workspace.
                    </Text>
                  </View>
                </SafeAreaView>
              )
            }

            const styles = StyleSheet.create({
              safe: {
                flex: 1,
                backgroundColor: '#121212',
                justifyContent: 'center',
                padding: 20,
              },
              card: {
                borderWidth: 1,
                borderColor: '#36302d',
                borderRadius: 24,
                padding: 24,
                backgroundColor: '#1b1b1b',
              },
              badge: {
                color: '#39d98a',
                fontSize: 12,
                fontWeight: '800',
                letterSpacing: 1,
              },
              title: {
                color: '#f7f3ef',
                fontSize: 34,
                fontWeight: '800',
                marginTop: 12,
              },
              body: {
                color: '#b8b0aa',
                fontSize: 16,
                lineHeight: 24,
                marginVertical: 16,
              },
              button: {
                minHeight: 48,
                borderRadius: 14,
                backgroundColor: '#ff6b00',
                alignItems: 'center',
                justifyContent: 'center',
                paddingHorizontal: 16,
              },
              buttonText: {
                color: '#121212',
                fontSize: 16,
                fontWeight: '800',
              },
              status: {
                color: '#39d98a',
                marginTop: 16,
                backgroundColor: '#101010',
                padding: 14,
                borderRadius: 14,
              },
            })
        """.trimIndent()
            .replace("__GOAL_JSON__", JSONObject.quote(safeGoal))
            .replace("__TITLE_JSON__", JSONObject.quote(name)) + "\n"

        val tsconfig = """
            {
              "extends": "expo/tsconfig.base",
              "compilerOptions": {
                "strict": true
              }
            }
        """.trimIndent() + "\n"

        val readme = """
            # __TITLE__

            React Native + Expo TypeScript source generated by Zip_Bug.

            zipbug.json is Zip_Bug metadata. app.json is the standard Expo config.

            ## Goal

            __GOAL__

            ## Safe build boundary

            Zip_Bug does not execute npm/npx lifecycle scripts from imported ZIPs.
            Review this project first, then build it in a workspace you trust.

            Typical Expo development commands are npm install and npx expo start.
            Android release packaging and signing remain explicit external steps;
            Zip_Bug does not create or overwrite signing credentials.

            Expo: 52.x
            React Native: 0.76.x
            React: 18.x
        """.trimIndent()
            .replace("__TITLE__", name)
            .replace(
                "__GOAL__",
                safeGoal.ifBlank { "No goal provided." }
            ) + "\n"

        return linkedMapOf(
            "zipbug.json" to manifest,
            "package.json" to packageJson,
            "app.json" to expoAppJson,
            "App.tsx" to appTsx,
            "tsconfig.json" to tsconfig,
            ".gitignore" to "node_modules/\n.expo/\ndist/\nweb-build/\n",
            "README.md" to readme
        )
    }
}
