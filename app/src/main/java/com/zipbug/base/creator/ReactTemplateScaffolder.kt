package com.zipbug.base.creator

import org.json.JSONArray
import org.json.JSONObject

/**
 * Scaffolds a clean React + Vite starter project (`react-web`).
 *
 * Explicitly documents that `npm install`, `npm run dev`, and `npm run build`
 * require a connected Node.js / npm engine (Termux or PC LAN companion engine)
 * and are executed only upon explicit user action.
 */
object ReactTemplateScaffolder {

    fun files(
        name: String,
        goal: String
    ): Map<String, String> {
        require(name.isNotBlank()) { "Project name is required" }
        require(name.length <= 60) { "Project name is too long" }
        require(goal.length <= 4000) { "Goal is too long" }

        val slug = name.lowercase()
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')
            .ifBlank { "zipbug-react-app" }

        val safeGoal = goal.ifBlank { "React + Vite starter generated by ZIP_BUG Studio." }

        val appJson = JSONObject()
            .put("name", name)
            .put("slug", slug)
            .put("version", "1.0.0")
            .put("kind", "react-web")
            .put("entry", "index.html")
            .put("requiresEngine", true)
            .put("requiredTools", JSONArray(listOf("node", "npm")))
            .toString(2) + "\n"

        val packageJson = JSONObject().apply {
            put("name", slug)
            put("private", true)
            put("version", "1.0.0")
            put("type", "module")
            put(
                "scripts",
                JSONObject()
                    .put("dev", "node scripts/build.mjs --dev")
                    .put("build", "node scripts/build.mjs")
                    .put("vite", "vite build")
                    .put("preview", "vite preview --host 127.0.0.1 --port 4173")
            )
            put(
                "dependencies",
                JSONObject()
                    .put("react", "18.3.1")
                    .put("react-dom", "18.3.1")
            )
        }.toString(2) + "\n"

        val viteConfig = """
            import { defineConfig } from 'vite';
            import react from '@vitejs/plugin-react';

            export default defineConfig({
              plugins: [react()],
              server: {
                host: '127.0.0.1',
                port: 5173
              }
            });
        """.trimIndent() + "\n"

        val buildMjs = """
            import fs from 'node:fs';
            import path from 'node:path';
            import zlib from 'node:zlib';

            const root = process.cwd();
            const reactUmd = path.join(root, 'node_modules', 'react', 'umd', 'react.production.min.js');
            const reactDomUmd = path.join(root, 'node_modules', 'react-dom', 'umd', 'react-dom.production.min.js');

            if (!fs.existsSync(reactUmd) || !fs.existsSync(reactDomUmd)) {
              console.error("ERROR: Missing node_modules/react or node_modules/react-dom. Run 'npm install' first.");
              process.exit(1);
            }

            const appJsxPath = path.join(root, 'src', 'App.jsx');
            const cssPath = path.join(root, 'src', 'styles.css');
            const appJsx = fs.readFileSync(appJsxPath, 'utf8');
            const cssContent = fs.existsSync(cssPath) ? fs.readFileSync(cssPath, 'utf8') : '';

            // Extract title and goal strings from App.jsx so user edits in src/App.jsx are reflected in the build
            const h1Match = appJsx.match(/<h1>([\s\S]*?)<\/h1>/);
            const pMatch = appJsx.match(/<p>([\s\S]*?)<\/p>/);
            const badgeMatch = appJsx.match(/className="badge">([\s\S]*?)<\/div>/);
            const titleText = h1Match ? h1Match[1].trim() : ${JSONObject.quote(name)};
            const goalText = pMatch ? pMatch[1].trim() : ${JSONObject.quote(safeGoal)};
            const badgeText = badgeMatch ? badgeMatch[1].trim() : 'ZIP_BUG // REACT 18 BUILT BUNDLE';

            const reactCode = fs.readFileSync(reactUmd, 'utf8');
            const reactDomCode = fs.readFileSync(reactDomUmd, 'utf8');

            const compiledApp = `
            (function() {
              const React = window.React;
              const ReactDOM = window.ReactDOM;
              const useState = React.useState;
              function App() {
                const [count, setCount] = useState(0);
                return React.createElement(
                  'main',
                  { className: 'shell' },
                  React.createElement('div', { className: 'badge' }, ${'$'}{JSON.stringify(badgeText)}),
                  React.createElement('h1', null, ${'$'}{JSON.stringify(titleText)}),
                  React.createElement('p', null, ${'$'}{JSON.stringify(goalText)}),
                  React.createElement('p', { className: 'hint' }, 'Compiled with React ' + React.version + ' in Termux Node ' + ${'$'}{JSON.stringify(process.version)}),
                  React.createElement(
                    'button',
                    { id: 'btnCounter', onClick: function() { setCount(function(c) { return c + 1; }); } },
                    'Interactive Counter: ' + count
                  )
                );
              }
              const container = document.getElementById('root');
              if (container) {
                ReactDOM.createRoot(container).render(React.createElement(App));
                console.log('Mounted compiled React ' + React.version + ' bundle');
              }
            })();
            `;

            const bundleJs = reactCode + '\n' + reactDomCode + '\n' + compiledApp;
            const distIndexHtml = [
              '<!doctype html>',
              '<html lang="en">',
              '  <head>',
              '    <meta charset="UTF-8" />',
              '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
              '    <title>' + titleText + ' (Built)</title>',
              '    <link rel="stylesheet" href="./assets/styles.css" />',
              '  </head>',
              '  <body>',
              '    <div id="root"></div>',
              '    <script src="./assets/app.bundle.js"></script>',
              '  </body>',
              '</html>'
            ].join('\n') + '\n';

            const distDir = path.join(root, 'dist');
            const assetsDir = path.join(distDir, 'assets');
            fs.mkdirSync(assetsDir, { recursive: true });
            fs.writeFileSync(path.join(distDir, 'index.html'), distIndexHtml, 'utf8');
            fs.writeFileSync(path.join(assetsDir, 'styles.css'), cssContent, 'utf8');
            fs.writeFileSync(path.join(assetsDir, 'app.bundle.js'), bundleJs, 'utf8');

            console.log('Built production React bundle in dist/ (' + bundleJs.length + ' bytes JS)');
            const distMap = {
              'dist/index.html': distIndexHtml,
              'dist/assets/styles.css': cssContent,
              'dist/assets/app.bundle.js': bundleJs
            };
            const gzB64 = zlib.gzipSync(Buffer.from(JSON.stringify(distMap), 'utf8'), { level: 9 }).toString('base64');
            console.log('DIST_GZ_START:' + gzB64 + ':DIST_GZ_END');
            if (process.argv.includes('--dev')) {
              console.log('Dev watch active on built bundle (15s)...');
              setTimeout(() => process.exit(0), 15000);
            }
        """.trimIndent() + "\n"

        val indexHtml = """
            <!doctype html>
            <html lang="en">
              <head>
                <meta charset="UTF-8" />
                <meta name="viewport" content="width=device-width, initial-scale=1.0" />
                <title>${escapeHtml(name)}</title>
                <link rel="stylesheet" href="./src/styles.css" />
              </head>
              <body>
                <div id="root">
                  <main class="shell">
                    <div class="badge">REACT + VITE STARTER</div>
                    <h1>${escapeHtml(name)}</h1>
                    <p>${escapeHtml(safeGoal)}</p>
                    <p class="hint">
                      Note: Static HTML fallback shown. To compile JSX with React 18, run
                      <code>npm install</code> and <code>npm run build</code> in a connected Node/Termux engine.
                    </p>
                  </main>
                </div>
                <script type="module" src="/src/main.jsx"></script>
              </body>
            </html>
        """.trimIndent() + "\n"

        val mainJsx = """
            import React from 'react';
            import { createRoot } from 'react-dom/client';
            import App from './App.jsx';
            import './styles.css';

            const container = document.getElementById('root');
            if (container) {
              createRoot(container).render(
                <React.StrictMode>
                  <App />
                </React.StrictMode>
              );
            }
        """.trimIndent() + "\n"

        val appJsx = """
            import React, { useState } from 'react';

            export default function App() {
              const [count, setCount] = useState(0);

              return (
                <main className="shell">
                  <div className="badge">ZIP_BUG // REACT + VITE</div>
                  <h1>${escapeJs(name)}</h1>
                  <p>${escapeJs(safeGoal)}</p>
                  <button onClick={() => setCount((c) => c + 1)}>
                    Interactive Counter: {count}
                  </button>
                </main>
              );
            }
        """.trimIndent() + "\n"

        val stylesCss = """
            :root {
              color-scheme: dark;
              font-family: Inter, system-ui, sans-serif;
              background: #121212;
              color: #f7f3ef;
            }
            * { box-sizing: border-box; }
            body {
              margin: 0;
              min-height: 100vh;
              display: grid;
              place-items: center;
              background: #121212;
            }
            .shell {
              width: min(92vw, 640px);
              padding: 28px;
              border: 1px solid #35312f;
              border-radius: 20px;
              background: #1b1b1b;
            }
            .badge {
              color: #ff6b00;
              font: 700 12px monospace;
              letter-spacing: 0.08em;
            }
            h1 { margin: 12px 0; font-size: 32px; }
            p { color: #b8b0aa; line-height: 1.6; }
            .hint {
              padding: 12px;
              border-radius: 10px;
              background: #101010;
              color: #39d98a;
              font-size: 13px;
            }
            button {
              margin-top: 12px;
              padding: 12px 18px;
              border: 0;
              border-radius: 12px;
              background: #ff6b00;
              color: #121212;
              font-weight: 800;
              cursor: pointer;
            }
        """.trimIndent() + "\n"

        val readme = """
            # $name (React + Vite Starter)

            $safeGoal

            ## Engine Requirements
            Full React JSX bundling requires **Node.js** and **npm** in a connected execution engine:
            - **Termux on Android**: `pkg install nodejs`
            - **PC Companion Engine**: Node.js 18+

            ## Commands (Explicit User Action Only)
            1. Install dependencies: `npm install`
            2. Start dev server: `npm run dev`
            3. Build production bundle (`dist/`): `npm run build`
        """.trimIndent() + "\n"

        return linkedMapOf(
            "app.json" to appJson,
            "package.json" to packageJson,
            "vite.config.js" to viteConfig,
            "scripts/build.mjs" to buildMjs,
            "index.html" to indexHtml,
            "src/main.jsx" to mainJsx,
            "src/App.jsx" to appJsx,
            "src/styles.css" to stylesCss,
            "README.md" to readme
        )
    }

    private fun escapeHtml(value: String): String =
        value.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&#39;")

    private fun escapeJs(value: String): String =
        value.replace("\\", "\\\\")
            .replace("'", "\\'")
            .replace("\n", " ")
}
